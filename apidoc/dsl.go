// toFloat accepts any Go numeric: hand-written fragments carry ints, JSON round
// trips carry float64. The check is KIND-based, so a named numeric type passes
// too; uintptr does not — it is an address, not a number.
func toFloat(v any) (float64, bool) {
	rv := reflect.ValueOf(v)
	if rv.Kind() == reflect.Uintptr {
		return 0, false
	}
	switch {
	case rv.CanInt():
		return float64(rv.Int()), true
	case rv.CanUint():
		return float64(rv.Uint()), true
	case rv.CanFloat():
		return rv.Float(), true
	}
	return 0, false
}

// toInt accepts any Go integer and an integral float (JSON has no int type).
func toInt(v any) (int, bool) {
	f, ok := toFloat(v)
	if !ok {
		return 0, false
	}
	i := int(f)
	if float64(i) != f {
		return 0, false
	}
	return i, true
}

// ---------------------------------------------------------------------------
// constructors / combinators
