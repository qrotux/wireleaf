// per-property deltas
// ---------------------------------------------------------------------------

// Nullable folds "null" into each key using the canonical OAS-3.1 idiom for the
// node's shape: scalar/enum/array/object → type-array (an enum also gains a
// null member); bare $ref → anyOf[$ref, null]; anyOf/oneOf → a null arm appended
// to the existing arms; allOf → the whole allOf WRAPPED as one arm of a new
// anyOf beside null (appending null to an allOf would demand the value be null
// AND everything else). Idempotent.
func (s Schema) Nullable(keys ...string) Schema {
	for _, k := range keys {
		p := s.mustProp(k)
		if p.Schema.Kind == KindOpaque {
			// irNullable cannot transform bytes it does not understand, and a
			// silent no-op is exactly what this DSL must never do. Wrap instead;
			// the result is a combinator, so a second call is idempotent through
			// the normal path.
			p.Schema = AnyOfNull(Schema{n: p.Schema}).n
			continue
		}
		p.Schema = irNullable(p.Schema)
	}
	return s
}

// NoFormat drops the format annotation.
func (s Schema) NoFormat(keys ...string) Schema {
	for _, k := range keys {
		s.mustProp(k).Schema.Format = ""
	}
	return s
}

// Ref REPLACES a property with a bare $ref to a named component.
func (s Schema) Ref(key, component string) Schema {
	s.mustProp(key).Schema = newRef(component)
	return s
}

// Enum REPLACES a property with a string enum over values.
func (s Schema) Enum(key string, values ...string) Schema {
	s.mustProp(key).Schema = newEnum("string", false, stringsToAny(values)...)
	return s
}

// NullableEnum REPLACES a property with a nullable string enum: "null" joins
// both the type list AND the enum members — without the null member the enum,
// the stricter of the two constraints, would make the null type unreachable.
func (s Schema) NullableEnum(key string, values ...string) Schema {
	s.mustProp(key).Schema = newEnum("string", true, stringsToAny(values)...)
	return s
}

// Describe sets a property's description.
func (s Schema) Describe(key, text string) Schema {
	p := s.mustProp(key)
	if p.Schema.Kind == KindOpaque {
		panic(fmt.Sprintf("apidoc: Describe(%q): property is an opaque fragment; put the description inside it", key))
	}
	p.Schema.Description = text
	return s
}

func stringsToAny(values []string) []any {
	out := make([]any, len(values))
	for i, v := range values {
		out[i] = v
	}
	return out
}

// OpenObject removes additionalProperties, leaving the object open.
func (s Schema) OpenObject() Schema {
	if s.n != nil {
		s.n.AdditionalProperties = nil
	}
	return s
}

// Pick projects properties onto keys (variant-view base); required follows the
// surviving keys. Surviving properties keep their relative order.
func (s Schema) Pick(keys ...string) Schema {
	keep := map[string]bool{}
	for _, k := range keys {
		s.mustProp(k)
		keep[k] = true
	}
	s.filterProps(func(name string) bool { return keep[name] })
	return s
}

// Omit drops keys from properties; required follows.
func (s Schema) Omit(keys ...string) Schema {
	drop := map[string]bool{}
	for _, k := range keys {
		s.mustProp(k)
		drop[k] = true
	}
	s.filterProps(func(name string) bool { return !drop[name] })
	return s
}

func (s Schema) filterProps(keep func(string) bool) {
	n := s.object()
	next := make([]Prop, 0, len(n.Props))
	for _, p := range n.Props {
		if keep(p.Name) {
			next = append(next, p)
		}
	}
	n.Props = next
}

