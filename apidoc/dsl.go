// Set is the enumerated escape hatch: a dotted path into the typed IR.
//
// Structural segments walk the node graph — "properties.<name>" descends into a
// property, "items" into an array's element schema, "anyOf.<i>"/"oneOf.<i>"/
// "allOf.<i>" into a combinator arm. The FINAL segment lands in its typed field
// (with a value-type check) or, for an "x-" key, in Extensions. A final
// "properties.<name>" naming a NEW property upserts it — the value may be a
// fragment map or a Schema, whose IR node is spliced in directly.
//
// Every failure panics at declaration time: an unresolvable path, a mistyped
// value, or a standard keyword outside the IR's typed set.
func (s Schema) Set(path string, v any) Schema {
	segs := strings.Split(path, ".")
	if s.n == nil {
		panic(fmt.Sprintf("apidoc: Set(%q): schema is empty", path))
	}
	setPath(s.n, path, segs, v)
	return s
}

func setPath(cur *IRNode, path string, segs []string, v any) {
	if cur == nil {
		panic(fmt.Sprintf("apidoc: Set(%q): path runs past a missing schema", path))
	}
	if cur.Kind == KindOpaque {
		panic(fmt.Sprintf("apidoc: Set(%q): cannot address inside an opaque fragment", path))
	}
	seg := segs[0]

	switch seg {
	case "properties":
		if cur.Kind != KindObject {
			panic(fmt.Sprintf("apidoc: Set(%q): segment %q: node is a %s, not an object", path, seg, cur.Kind))
		}
		if len(segs) < 2 {
			panic(fmt.Sprintf("apidoc: Set(%q): %q needs a property name", path, seg))
		}
		name := segs[1]
		idx := -1
		for i := range cur.Props {
			if cur.Props[i].Name == name {
				idx = i
				break
			}
		}
		if len(segs) == 2 {
			// Final segment: replace or UPSERT (a reflector may emit no property
			// at all for an `any`-typed field).
			child := setValueNode(path, v)
			if idx >= 0 {
				cur.Props[idx].Schema = child
			} else {
				cur.Props = append(cur.Props, Prop{Name: name, Schema: child})
			}
			return
		}
		if idx < 0 {
			panic(fmt.Sprintf("apidoc: Set(%q): unknown property %q in schema (have %v)", path, name, Schema{n: cur}.propNames()))
		}
		setPath(cur.Props[idx].Schema, path, segs[2:], v)
		return

	case "anyOf", "oneOf", "allOf":
		arms := cur.AnyOf
		switch seg {
		case "oneOf":
			arms = cur.OneOf
		case "allOf":
			arms = cur.AllOf
		}
		if len(segs) == 1 {
			break // leaf: fall through to the keyword setter
		}
		i, err := strconv.Atoi(segs[1])
		if err != nil {
			panic(fmt.Sprintf("apidoc: Set(%q): %q needs an arm index, got %q", path, seg, segs[1]))
		}
		if i < 0 || i >= len(arms) {
			panic(fmt.Sprintf("apidoc: Set(%q): %s index %d is out of range (%d arms)", path, seg, i, len(arms)))
		}
		if len(segs) == 2 {
			arms[i] = setValueNode(path, v)
			return
		}
		setPath(arms[i], path, segs[2:], v)
		return

	case "items":
		if len(segs) == 1 {
			break // leaf: fall through to the keyword setter
		}
		if cur.Items == nil {
			panic(fmt.Sprintf("apidoc: Set(%q): node has no items schema", path))
		}
		setPath(cur.Items, path, segs[1:], v)
		return

	case "not":
		if len(segs) == 1 {
			break
		}
		if cur.Not == nil {
			panic(fmt.Sprintf("apidoc: Set(%q): node has no not schema", path))
		}
		setPath(cur.Not, path, segs[1:], v)
		return
	}

	if len(segs) != 1 {
		panic(fmt.Sprintf("apidoc: Set(%q): segment %q does not address a schema", path, seg))
	}
	if err := assignKeyword(cur, seg, v); err != nil {
		panic(fmt.Sprintf("apidoc: Set(%q): %s", path, err))
	}
	if err := cur.checkInvariants(); err != nil {
		panic(fmt.Sprintf("apidoc: Set(%q): %s", path, err))
	}
}

// setValueNode turns a Set value into a node: a Schema splices its IR directly
// (composition without RefPrefix string concatenation), a map is parsed like a
// RawFragment.
func setValueNode(path string, v any) *IRNode {
	// STRICT: Set is a typed ingress path, so an exotic fragment is an error
	// here rather than a silent Opaque. RawFragment is where exotica belongs.
	n, err := fragChild(v, true)
	if err != nil {
		panic(fmt.Sprintf("apidoc: Set(%q): mistyped value: %s", path, err))
	}
	if n == nil {
		panic(fmt.Sprintf("apidoc: Set(%q): mistyped value: schema is nil", path))
	}
	return n
}

// ---------------------------------------------------------------------------
// keyword assignment (shared by fragmentToIR and Set)
// ---------------------------------------------------------------------------

func mistyped(key, want string, v any) error {
	return fmt.Errorf("mistyped value for %q: want %s, got %T", key, want, v)
}

// assignKeyword writes one keyword into its typed field, with a value-type
// check. "x-" keys land in Extensions; a standard keyword the IR does not model
// (and any other unknown key) is rejected — the typed ingress paths refuse
// exotica, RawFragment is where an opaque fragment belongs.
func assignKeyword(n *IRNode, key string, v any) error {
	if strings.HasPrefix(key, "x-") {
		// SetExtension is the ONE implementation: it validates the key and
		// re-collects extRefs over the whole map, so components assembly's
		// dangling-ref check sees a "$ref" hiding inside an extension value no
		// matter which writer put it there.
		return n.SetExtension(key, v)
	}

	switch key {
	case "$ref":
		s, ok := v.(string)
		if !ok {
			return mistyped(key, "string", v)
		}
		n.Ref = strings.TrimPrefix(s, RefPrefix)
		return nil

	case "type":
		types, err := fragTypes(v)
		if err != nil {
			return fmt.Errorf("mistyped value for %q: %w", key, err)
		}
		n.Types = types
		return nil

	case "enum":
		vals, ok := v.([]any)
		if !ok {
			return mistyped(key, "[]any", v)
		}
		n.Enum = append([]any(nil), vals...)
		if n.Kind == KindScalar {
			n.Kind = KindEnum
		}
		return nil

	case "required":
		if n.Kind != KindObject {
			return fmt.Errorf(`"required" needs an object node, got %s`, n.Kind)
		}
		names, err := fragStrings(v)
		if err != nil {
			return fmt.Errorf("mistyped value for %q: %w", key, err)
		}
		for i := range n.Props {
			n.Props[i].Required = false
		}
		return fragApplyRequired(n, names)

	case "items":
		child, err := fragChild(v, true)
		if err != nil {
			return fmt.Errorf("mistyped value for %q: %w", key, err)
		}
		n.Items = child
		return nil

	case "not":
		child, err := fragChild(v, true)
		if err != nil {
			return fmt.Errorf("mistyped value for %q: %w", key, err)
		}
		n.Not = child
		return nil

	case "additionalProperties":
		ap, err := fragAdditionalProperties(v, true)
		if err != nil {
			return fmt.Errorf("mistyped value for %q: %w", key, err)
		}
		n.AdditionalProperties = ap
		return nil

	case "properties", "anyOf", "oneOf", "allOf":
		return fmt.Errorf("%q must be addressed one member at a time (e.g. %s.<member>)", key, key)

	case "const":
		n.Const = v
		return nil
	case "default":
		n.Default = v
		return nil
	case "examples":
		vals, ok := v.([]any)
		if !ok {
			return mistyped(key, "[]any", v)
		}
		n.Examples = append([]any(nil), vals...)
		return nil
	case "dependentRequired":
		dr, ok := v.(map[string][]string)
		if !ok {
			return mistyped(key, "map[string][]string", v)
		}
		n.DependentRequired = dr
		return nil
	}

	if target, ok := stringField(n, key); ok {
		s, ok := v.(string)
		if !ok {
			return mistyped(key, "string", v)
		}
		*target = s
		return nil
	}
	if target, ok := boolField(n, key); ok {
		b, ok := v.(bool)
		if !ok {
			return mistyped(key, "bool", v)
		}
		*target = b
		return nil
	}
	if target, ok := floatField(n, key); ok {
		f, ok := toFloat(v)
		if !ok {
			return mistyped(key, "number", v)
		}
		*target = &f
		return nil
	}
	if target, ok := intField(n, key); ok {
		i, ok := toInt(v)
		if !ok {
			return mistyped(key, "integer", v)
		}
		*target = &i
		return nil
	}

	if standardKeywords[key] {
		return fmt.Errorf("standard keyword %q is outside the typed set", key)
	}
	return fmt.Errorf("keyword %q is outside the typed set (only x- extensions may be unknown)", key)
}

func stringField(n *IRNode, key string) (*string, bool) {
	switch key {
	case "pattern":
		return &n.Pattern, true
	case "format":
		return &n.Format, true
	case "description":
		return &n.Description, true
	case "title":
		return &n.Title, true
	case "contentEncoding":
		return &n.ContentEncoding, true
	case "contentMediaType":
		return &n.ContentMediaType, true
	}
	return nil, false
}

