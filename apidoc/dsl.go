// ---------------------------------------------------------------------------
// property access
// ---------------------------------------------------------------------------

// object returns the underlying node, panicking unless it is an object — every
// delta below targets an object schema produced by a Reflector or a literal.
func (s Schema) object() *IRNode {
	if s.n == nil || s.n.Kind != KindObject {
		panic(fmt.Sprintf("apidoc: schema has no properties map (fragment: %v)", s.Map()))
	}
	return s.n
}

// propNames returns the receiver's property names, sorted (panic messages must
// be stable regardless of Props order).
func (s Schema) propNames() []string {
	n := s.object()
	names := make([]string, 0, len(n.Props))
	for _, p := range n.Props {
		names = append(names, p.Name)
	}
	sort.Strings(names)
	return names
}

// mustProp panics unless key exists in properties — a typo in a delta must be
// an instant unit-test failure, never a silent no-op.
func (s Schema) mustProp(key string) *Prop {
	n := s.object()
	for i := range n.Props {
		if n.Props[i].Name == key {
			return &n.Props[i]
		}
	}
	panic(fmt.Sprintf("apidoc: unknown property %q in schema (have %v)", key, s.propNames()))
}

// ---------------------------------------------------------------------------
// required
// ---------------------------------------------------------------------------

// Required REPLACES the required set with exactly keys. Every key must exist.
//
// The emitted `required` list follows PROPERTY order, not the caller's argument
// order — the IR derives the list from the Prop.Required flags.
func (s Schema) Required(keys ...string) Schema {
	props := make([]*Prop, 0, len(keys))
	for _, k := range keys {
		props = append(props, s.mustProp(k))
	}
	n := s.object()
	for i := range n.Props {
		n.Props[i].Required = false
	}
	for _, p := range props {
		p.Required = true
	}
	return s
}

// RequireAlso ADDS keys to the existing required set, leaving the current
// members in place. Every key must exist in properties.
//
// This is the additive counterpart of Required, which REPLACES. Reach for it
// whenever the current set was not written literally at the call site — e.g.
// after a merge that builds a required UNION: calling Required there silently
// discards that union and leaves a component with one required key, a failure
// invisible to tests that compare against a document regenerated by the same
// code path.
func (s Schema) RequireAlso(keys ...string) Schema {
	for _, k := range keys {
		s.mustProp(k).Required = true
	}
	return s
}

// Optional removes keys from required. Keys must exist in properties (typo
// guard); removing a non-required key is a no-op.
func (s Schema) Optional(keys ...string) Schema {
	for _, k := range keys {
		s.mustProp(k).Required = false
	}
	return s
}

// RequiredAll marks every current property required.
//
// The emitted list follows Props order: for a RawFragment-built object that is
// sorted key order, for a reflected object it is field order.
func (s Schema) RequiredAll() Schema {
	n := s.object()
	for i := range n.Props {
		n.Props[i].Required = true
	}
	return s
}

