// RefTo is a bare $ref to a named component.
func RefTo(component string) Schema { return Schema{n: newRef(component)} }

// AllOf composes parts by reference (single-owner convention).
func AllOf(parts ...Schema) Schema { return Schema{n: newAllOf(armNodes("AllOf", parts)...)} }

// OneOf composes parts by reference (sum-type document arm; the status and
// marshalling half of a sum type lives in the application's operation layer).
func OneOf(parts ...Schema) Schema { return Schema{n: newOneOf(armNodes("OneOf", parts)...)} }

// AnyOf composes parts by reference (polymorphic whole-body or restricted-arm
// document, as used by BodySchemaProvider bodies).
func AnyOf(parts ...Schema) Schema { return Schema{n: newAnyOf(armNodes("AnyOf", parts)...)} }

func armNodes(verb string, parts []Schema) []*IRNode {
	out := make([]*IRNode, len(parts))
	for i, p := range parts {
		if p.n == nil {
			panic(fmt.Sprintf("apidoc: %s: part %d is an empty Schema", verb, i))
		}
		out[i] = p.n
	}
	return out
}

// AnyOfNull composes anyOf[inner, {type:"null"}], for building nullable inline
// objects and enums passed to Set. Idempotent: if inner is already an anyOf
// carrying a null arm, it is returned unchanged.
func AnyOfNull(inner Schema) Schema {
	if inner.n == nil {
		panic("apidoc: AnyOfNull: empty Schema")
	}
	if inner.n.Kind == KindCombinator && hasNullArm(inner.n.AnyOf) {
		return inner
	}
	return Schema{n: newAnyOf(inner.n, newScalar("null"))}
}

// AnyOfNull rewrites each named property to anyOf[<current>, {type:null}] — the
// form reflected enums, $refs and inline objects take in the committed document.
func (s Schema) AnyOfNull(keys ...string) Schema {
	for _, k := range keys {
		p := s.mustProp(k)
		p.Schema = AnyOfNull(Schema{n: p.Schema}).n
	}
	return s
}
