// names returns every component name in the shared set, sorted. apidoc.Merge is
// the only exported enumeration seam over a Components; it is used HERE ONLY —
// on the document-emission path, never per registration or per request.
func (b *Registry) names() []string {
	scratch := map[string]any{}
	if err := b.c.Merge(scratch); err != nil {
		panic(fmt.Sprintf("adapters/huma: reading components: %v", err))
	}
	out := make([]string, 0, len(scratch))
	for name := range scratch {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

// schemaFor converts one component to huma form, cached.
//
// SERVING RULE: a component is served TYPED — the full converter, so huma both
// documents and VALIDATES it — only when its Go wire type is known and is a
// struct. Otherwise it is served through the Extensions bridge, as one opaque
// fragment.
//
// The reason is huma's SchemaLinkTransformer (installed by DefaultConfig). For
// every response body whose schema has "type":"object" it builds a wrapper Go
// struct out of deref(registry.TypeFromRef(ref)) and reads its fields
// (transforms.go:110) — with no nil check, and outside its own recover(). A
// component with no wire type can NEVER satisfy TypeFromRef, so serving it typed
// in response position is a guaranteed panic at huma.Register. Serving it opaque
// leaves Type == "", which makes the transformer bail one line earlier and skip
// it. The same holds for a component bound to a non-struct type: NumField would
// panic on the very same line.
//
// The served document is byte-identical either way.
//
// CONCURRENCY: the cache is read and written under mu; the conversion itself
// runs unlocked over the immutable IR, and a racing duplicate is resolved on
// insert so every caller for a name gets the same *humav2.Schema pointer.
func (b *Registry) schemaFor(name string) *humav2.Schema {
	b.mu.RLock()
	s, ok := b.converted[name]
	b.mu.RUnlock()
	if ok {
		return s
	}
	entry, ok := b.c.Get(name)
	if !ok {
		return nil
	}
	if servableAsType(b.TypeFromRef(apidoc.RefPrefix + name)) {
		var err error
		if s, err = toHuma(entry.IR()); err != nil {
			panic(fmt.Sprintf("adapters/huma: converting component %q: %v", name, err))
		}
	} else {
		s = opaqueSchema(name, entry.IR())
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if prev, ok := b.converted[name]; ok {
		return prev // a concurrent caller won the race; one schema per name
	}
	b.converted[name] = s
	return s
}

// servableAsType reports whether huma's response-body machinery can build a
// wrapper struct from t.
func servableAsType(t reflect.Type) bool {
	return apidoc.DerefType(t) != nil && apidoc.DerefType(t).Kind() == reflect.Struct
}

// opaqueSchema renders a component as one Extensions-bridge fragment: a zero
// typed Schema whose Extensions hold the whole thing marshals to exactly it.
func opaqueSchema(name string, n *apidoc.IRNode) *humav2.Schema {
	raw, err := n.MarshalJSON()
	if err != nil {
		panic(fmt.Sprintf("adapters/huma: serializing component %q: %v", name, err))
	}
	var m map[string]any
	if err := json.Unmarshal(raw, &m); err != nil {
		panic(fmt.Sprintf("adapters/huma: component %q is not a JSON object: %v", name, err))
	}
	s := &humav2.Schema{Extensions: m}
	s.PrecomputeMessages()
	return s
}

// answer returns either a reference to the named component or its full schema.
func (b *Registry) answer(name string, allowRef bool) *humav2.Schema {
	if allowRef {
		return &humav2.Schema{Ref: apidoc.RefPrefix + name}
	}
	return b.schemaFor(name)
}

