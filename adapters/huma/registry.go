package huma

// registry.go — the read-write humav2.Registry bridge.
//
// wireleaf is the schema authority: huma keeps no schema map of its own. Every schema huma asks for is answered from the shared
// apidoc.Components — either a component wireleaf already owns, or one produced
// on demand by the canonical reflector and registered INTO the shared set. That
// is what makes huma-originated types (ErrorModel, input structs, nested body
// types) part of the same document as the graph-derived components.
//
// The shared set holds TYPED IR on both sides of the bridge: components enter
// through apidoc.Components.RegisterReflected (which owns idempotence — an
// identical re-registration is a no-op, a conflicting one an error) and are read
// back through Components.Get. There is no bridge-side shadow of the entries and
// no map round trip in either direction.
//
// BOUNDARY IDIOM — non-struct types. A type wireleaf does not model as a
// component (a scalar, slice, map, time.Time, url.URL, or anything providing its
// own schema) is generated by huma's own SchemaFromType, recursing back through
// this bridge so nested component-worthy types still land in the shared set.
// That path is huma's, not wireleaf's, and it differs in places: a top-level
// []T body is NULLABLE under huma's DefaultArrayNullable, whereas a []T STRUCT
// FIELD goes through the canonical reflector and the wireleaf nullability
// policy. The divergence is confined to the top level of a non-struct body.
//
// LIMITATION — huma's registryConfig (Config.AllowAdditionalPropertiesByDefault,
// Config.FieldsOptionalByDefault) is applied by huma only to its own
// *mapRegistry, so both options are silently INERT against this bridge:
// additional-properties and required-ness are the canonical reflector's verdict,
// and NewConfig exposes neither option.
//
// NOTE — the canonical reflector deliberately does NOT emit
// "additionalProperties": false, while stock huma does for structs. A body
// validated by wireleaf's components therefore accepts unknown properties where
// stock huma would have rejected them. That is canon, not an oversight.

import (
	"encoding"
	"encoding/json"
	"fmt"
	"net/url"
	"reflect"
	"sort"
	"strings"
	"sync"
	"time"

	humav2 "github.com/danielgtaylor/huma/v2"

	"github.com/qrotux/wireleaf/apidoc"
)

var (
	timeType            = reflect.TypeFor[time.Time]()
	urlType             = reflect.TypeFor[url.URL]()
	schemaProviderType  = reflect.TypeFor[humav2.SchemaProvider]()
	textUnmarshalerType = reflect.TypeFor[encoding.TextUnmarshaler]()
)

// Registry bridges huma's schema registry onto a shared apidoc.Components plus
// the canonical reflector.
//
// CONCURRENCY. Registration (Schema, RegisterTypeAlias) happens at startup
// wiring time and is NOT safe to run concurrently with itself. Serving is not
// read-only, though: SchemaFromRef is on huma's request-validation path and
// populates a lazy conversion cache, so it can run from many request goroutines
// at once. The maps it touches — converted (written by schemaFor) and types
// (read by TypeFromRef) — are therefore guarded by mu. aliases is
// registration-time only (written by RegisterTypeAlias, read by Schema) and
// stays unguarded, as does the shared *apidoc.Components, which is likewise
// only written during wiring and only read while serving.
type Registry struct {
	c *apidoc.Components
	r apidoc.Reflector

	// mu guards converted and types — the two maps that a request-time
	// SchemaFromRef can reach. See the CONCURRENCY note above.
	mu sync.RWMutex

	// types is the component name → owning Go type index behind TypeFromRef. It
	// covers everything THIS bridge registered, auxiliaries included;
	// application-registered components are found through the shared index
	// instead (Components.TypeOf). GUARDED by mu: written at registration time,
	// read on the request path through schemaFor.
	types map[string]reflect.Type
	// aliases implements RegisterTypeAlias. UNGUARDED: registration-time only.
	aliases map[reflect.Type]reflect.Type
	// converted caches the huma form per component name — SchemaFromRef is on
	// huma's request-validation hot path. A component's content never changes
	// once registered (Add rejects a duplicate, RegisterReflected requires an
	// identical IR), so the cache needs no invalidation. GUARDED by mu: this is
	// the one map written while serving.
	converted map[string]*humav2.Schema
}

var (
	_ humav2.Registry = (*Registry)(nil)
	_ json.Marshaler  = (*Registry)(nil)
)

// NewRegistry returns the bridge over c and r. Both are required.
func NewRegistry(c *apidoc.Components, r apidoc.Reflector) humav2.Registry {
	if c == nil {
		panic("adapters/huma: NewRegistry: nil Components")
	}
	if r == nil {
		panic("adapters/huma: NewRegistry: nil Reflector")
	}
	return &Registry{
		c:         c,
		r:         r,
		types:     map[string]reflect.Type{},
		aliases:   map[reflect.Type]reflect.Type{},
		converted: map[string]*humav2.Schema{},
	}
}

// Components exposes the shared component set the bridge writes into.
func (b *Registry) Components() *apidoc.Components { return b.c }

