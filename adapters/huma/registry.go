// reflectAndRegister reflects t through the canonical reflector and registers
// every component it produced. Returns the top component's name.
func (b *Registry) reflectAndRegister(t reflect.Type, hint string) string {
	b.assertNoNodeWrappers(t)
	name := componentName(t, hint)
	comps, err := b.r.ReflectComponents([]reflect.Type{t}, map[reflect.Type]string{t: name})
	if err != nil {
		panic(fmt.Sprintf("adapters/huma: reflecting %v into component %q: %v", t, name, err))
	}
	if _, ok := comps[name]; !ok {
		// The usual cause is an ANONYMOUS struct: the reflection engine inlines
		// a root anonymous struct instead of defining it, so the requested name
		// is never produced. Naming the type is the fix, and the message says so
		// rather than leaving a caller to infer it from a missing key.
		panic(fmt.Sprintf("adapters/huma: reflector did not return the requested component %q for %v "+
			"(an anonymous struct cannot be reflected into a component — use a named body type)", name, t))
	}
	names := make([]string, 0, len(comps))
	for n := range comps {
		names = append(names, n)
	}
	sort.Strings(names) // deterministic error on a conflicting set

	// Every component gets its owning Go type, auxiliaries included. huma needs
	// the type back for any component it serves as a response body (see
	// schemaFor), and an auxiliary here is just a nested struct that another
	// operation may well use as a body of its own.
	owners := auxTypes(t)
	for _, n := range names {
		owner := owners[n]
		if n == name {
			owner = t // the requested type owns the requested name, whatever it is called
		}
		if err := b.c.RegisterReflected(n, comps[n], owner); err != nil {
			panic(fmt.Sprintf("adapters/huma: registering component %q for %v: %v", n, t, err))
		}
		if owner != nil {
			b.mu.Lock()
			b.types[n] = owner
			b.mu.Unlock()
		}
	}
	return name
}

// assertNoNodeWrappers is a LOUD startup guard on the reflection path.
//
// A node wrapper carries its payload in an unexported field: the canonical
// reflector, which knows nothing about nodes, sees a struct with zero exported
// fields and emits an empty object. That is a silently wrong contract — the
// document would promise {} where the engine sends a whole resource — so a
// wrapper reached from a type on its way to the reflector STOPS the wiring
// instead.
//
// A node legitimately appears only where the bridge itself resolves it: as an
// envelope's data field (envelope.go's convention), as an open-page extra field
// routed back through Schema, or as a body type of its own (which never reaches
// here — the NodeComponent lookup in Schema answers first).
//
// SCOPE: the walk is transitive, so an ENVELOPE nested inside a plain struct
// panics too. That is deliberate. Reached as a field, an envelope struct is
// reflected as an ordinary struct (the derivation runs on the type the bridge is
// ASKED for, not on the types it walks into), so the document would promise
// {data:{}} — the same silent lie, one level down. Compose envelopes at the body
// type, not inside one.
func (b *Registry) assertNoNodeWrappers(root reflect.Type) {
	seen := map[reflect.Type]bool{}
	var walk func(reflect.Type)
	walk = func(cur reflect.Type) {
		cur = apidoc.DerefType(cur)
		if cur == nil || seen[cur] {
			return
		}
		seen[cur] = true
		switch cur.Kind() {
		case reflect.Slice, reflect.Array, reflect.Map:
			walk(cur.Elem())
		case reflect.Struct:
			for i := range cur.NumField() {
				f := cur.Field(i)
				if !f.IsExported() || f.Tag.Get("json") == "-" {
					continue
				}
				if wrapper, ok := b.nodeWrapperIn(f.Type); ok {
					panic(fmt.Sprintf(
						"adapters/huma: node wrapper %v reached the canonical reflector via %v.%s; "+
							"nodes may only appear as an envelope data field (or an open-page extra routed through the bridge)",
						wrapper, cur, f.Name))
				}
				walk(f.Type)
			}
		}
	}
	walk(root)
}

// nodeWrapperIn unwraps pointers, slices, arrays and maps down to the value
// type and reports whether it is a registered node wrapper.
func (b *Registry) nodeWrapperIn(t reflect.Type) (reflect.Type, bool) {
	for {
		t = apidoc.DerefType(t)
		if t == nil {
			return nil, false
		}
		if _, ok := b.c.NodeComponent(t); ok {
			return t, true
		}
		switch t.Kind() {
		case reflect.Slice, reflect.Array, reflect.Map:
			t = t.Elem()
		default:
			return nil, false
		}
	}
}

// registerDerived registers a DERIVED component (a success envelope) under the
// name huma's namer gives t, bound to t so the bridge serves it typed and huma
// can build the Go type back from the $ref. The binding also short-circuits the
// derivation on the next request for t: the TypeName lookup in Schema answers
// first.
func (b *Registry) registerDerived(t reflect.Type, hint string, ir *apidoc.IRNode) string {
	name := componentName(t, hint)
	if err := b.c.RegisterReflected(name, ir, t); err != nil {
		panic(fmt.Sprintf("adapters/huma: registering derived component %q for %v: %v", name, t, err))
	}
	b.mu.Lock()
	b.types[name] = t
	b.mu.Unlock()
	return name
}

// auxTypes walks t's wire shape and indexes the struct types it reaches under
// the names the canonical reflector gives them (the Go type name — see the
// reflector's defName). It is how an auxiliary component gets its owning type
// back: ReflectComponents returns names and IR, not types.
//
// A type the reflector would not turn into a component of its own
// (time.Time, a SchemaProvider, …) is skipped — approximately as it is skipped
// there: componentWorthy is huma's rule, not the reflector's, and the two
// differ on url.URL, humav2.SchemaProvider and encoding.TextUnmarshaler. The
// consequence of a disagreement is a missing owner type for an auxiliary, which
// degrades that component to opaque serving (see schemaFor), never a wrong one.
func auxTypes(t reflect.Type) map[string]reflect.Type {
	out := map[string]reflect.Type{}
	seen := map[reflect.Type]bool{}
	var walk func(reflect.Type)
	walk = func(cur reflect.Type) {
		cur = apidoc.DerefType(cur)
		if cur == nil || seen[cur] {
			return
		}
		seen[cur] = true
		switch cur.Kind() {
		case reflect.Slice, reflect.Array:
			walk(cur.Elem())
		case reflect.Map:
			walk(cur.Elem())
		case reflect.Struct:
			if !componentWorthy(cur) {
				return
			}
			if n := cur.Name(); n != "" {
				if _, taken := out[n]; !taken {
					out[n] = cur
				}
			}
			for i := range cur.NumField() {
				f := cur.Field(i)
				if !f.IsExported() || f.Tag.Get("json") == "-" {
					continue
				}
				walk(f.Type)
			}
		}
	}
	walk(t)
	return out
}

