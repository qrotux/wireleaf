// Schema answers huma's schema request for t. Order matters:
//  1. a type registered through RegisterTypeAlias resolves as its alias
//     (the lookup recurses, so the alias walks the rest of this list);
//  2. a node WRAPPER type resolves to the component its wire type owns;
//  3. a type already bound to a component name resolves to that component;
//  4. a struct matching the success-envelope convention (envelope.go) is
//     DERIVED as an envelope — before any reflection, so the document describes
//     the envelope rather than the Go field shape;
//  5. a type wireleaf does not model as a component is generated inline by huma
//     itself — see the boundary-idiom note at the top of this file;
//  6. anything else is reflected through the canonical reflector and every
//     component it returns (the top AND the auxiliaries) is registered.
//
// A reflection or registration failure PANICS: this runs at startup wiring
// time, where a half-built document is worse than a loud stop.
func (b *Registry) Schema(t reflect.Type, allowRef bool, hint string) *humav2.Schema {
	orig := t
	t = apidoc.DerefType(t)
	if t == nil {
		panic("adapters/huma: Registry.Schema: nil type")
	}
	if alias, ok := b.aliases[t]; ok {
		return b.Schema(alias, allowRef, hint)
	}
	if name, ok := b.c.NodeComponent(t); ok {
		return b.answer(name, allowRef)
	}
	if name, ok := b.c.TypeName(t); ok {
		return b.answer(name, allowRef)
	}
	// The success-envelope data convention (envelope.go) is checked BEFORE the
	// canonical reflection: a body struct matching it documents an envelope,
	// not its Go field shape. Everything else falls through untouched.
	if ir, ok := b.envelopeIR(t, hint); ok {
		return b.answer(b.registerDerived(t, hint, ir), allowRef)
	}
	if !componentWorthy(t) {
		return humav2.SchemaFromType(b, orig)
	}
	return b.answer(b.reflectAndRegister(t, hint), allowRef)
}

// SchemaFromRef resolves a "#/components/schemas/X" reference. It is on huma's
// request-validation hot path, so the conversion is cached.
func (b *Registry) SchemaFromRef(ref string) *humav2.Schema {
	if !strings.HasPrefix(ref, apidoc.RefPrefix) {
		return nil
	}
	return b.schemaFor(strings.TrimPrefix(ref, apidoc.RefPrefix))
}

// TypeFromRef is the inverse index: the Go type a component was registered for,
// or the zero reflect.Type when it has none (an auxiliary the reflector named on
// its own, or a component assembled by hand).
//
// It consults the SHARED type index as well as the bridge's own, so a component
// the application registered together with its wire type (RegisterType, or
// RegisterNode's binding of W) answers here too. huma builds a Go struct type
// from this when it serves a response body, so an answer that exists must be
// found — see schemaFor for what happens when none does.
func (b *Registry) TypeFromRef(ref string) reflect.Type {
	name := strings.TrimPrefix(ref, apidoc.RefPrefix)
	b.mu.RLock()
	t, ok := b.types[name]
	b.mu.RUnlock()
	if ok {
		return t
	}
	if t, ok := b.c.TypeOf(name); ok {
		return t
	}
	return nil
}

// Map renders the WHOLE shared component set — the bridge's own registrations
// and everything the application registered directly — in huma form. The map is
// rebuilt per call from the live Components; mutating it does not write back.
func (b *Registry) Map() map[string]*humav2.Schema {
	out := map[string]*humav2.Schema{}
	for _, name := range b.names() {
		if s := b.schemaFor(name); s != nil {
			out[name] = s
		}
	}
	return out
}

// RegisterTypeAlias makes the bridge answer for t as if it were alias.
func (b *Registry) RegisterTypeAlias(t reflect.Type, alias reflect.Type) {
	b.aliases[apidoc.DerefType(t)] = alias
}

// MarshalJSON serves the components/schemas object of the document: huma
// marshals Components.Schemas through this. It agrees with Map by construction,
// which matters because huma's unused-schema pruning marshals Map's result
// directly instead.
func (b *Registry) MarshalJSON() ([]byte, error) { return json.Marshal(b.Map()) }

// MarshalYAML mirrors mapRegistry's. huma's own YAML path goes through JSON, so
// nothing in huma calls this; it exists so the bridge is a drop-in for code that
// marshals a registry with a YAML encoder.
func (b *Registry) MarshalYAML() (any, error) { return b.Map(), nil }

