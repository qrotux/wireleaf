// componentWorthy reports whether t is a type wireleaf renders as a NAMED
// component. It follows huma's own getsRef rule so the two registries agree on
// what earns a $ref, and it keeps non-struct types away from the reflector,
// which only reflects structs.
//
// It is huma's rule, so it matches the canonical reflector's notion of a
// definition only APPROXIMATELY: url.URL, humav2.SchemaProvider implementors
// and encoding.TextUnmarshaler implementors are excluded here on huma's
// authority, and the reflector may or may not treat them the same way.
func componentWorthy(t reflect.Type) bool {
	if t.Kind() != reflect.Struct || t == timeType || t == urlType {
		return false
	}
	pt := reflect.PointerTo(t)
	for _, iface := range []reflect.Type{schemaProviderType, textUnmarshalerType} {
		if t.Implements(iface) || pt.Implements(iface) {
			return false
		}
	}
	return true
}

// componentName is huma's naming rule, which agrees with the reflector's own
// default (the Go type name) for ordinary named structs and supplies huma's
// hint-derived name for anonymous ones.
func componentName(t reflect.Type, hint string) string {
	return humav2.DefaultSchemaNamer(t, hint)
}
